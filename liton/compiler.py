"""Compiler: turn a :class:`StrategyPlan` into artifacts on disk.

The output is deliberately plain: a shell runner, an environment file, an
installer script and (for container plans) a Dockerfile.  Everything is
reproducible and inspectable, which is what makes a profile trustworthy.
"""

from __future__ import annotations

import json
import os
import shlex
import stat
from pathlib import Path

from .models import Analysis, Profile, StrategyPlan
from .foreign import Translator

HEADER = "# Generated by Liton - do not edit; re-run `liton translate` instead."


def _sh_quote(value: str) -> str:
    return shlex.quote(str(value))


def compile_env(plan: StrategyPlan) -> str:
    lines = [HEADER, "# Environment applied before launch."]
    for key, value in sorted(plan.env.items()):
        lines.append(f"export {key}={_sh_quote(value)}")
    if plan.ld_library_path:
        joined = ":".join(plan.ld_library_path)
        lines.append(f'export LD_LIBRARY_PATH={_sh_quote(joined)}:"$LD_LIBRARY_PATH"')
    if plan.preload:
        joined = ":".join(plan.preload)
        lines.append(f'export LD_PRELOAD={_sh_quote(joined)}:"$LD_PRELOAD"')
    lines.append("")
    return "\n".join(lines)


def compile_install(plan: StrategyPlan) -> str:
    lines = ["#!/bin/sh", HEADER]
    if not plan.packages:
        lines.append("# No extra packages required.")
        lines.append("exit 0")
        lines.append("")
        return "\n".join(lines)

    lines += [
        "set -e",
        "# Install the Debian packages that provide the missing shared libraries.",
        "if command -v apt-get >/dev/null 2>&1; then",
        "  SUDO=''",
        "  [ \"$(id -u)\" -eq 0 ] || SUDO='sudo'",
        "  $SUDO apt-get update",
        f"  $SUDO apt-get install -y {shlex.join(plan.packages)}",
        "else",
        "  echo 'apt-get not found; install these packages with your package manager:' >&2",
        f"  echo '  {shlex.join(plan.packages)}' >&2",
        "  exit 1",
        "fi",
        "",
    ]
    return "\n".join(lines)


def compile_dockerfile(plan: StrategyPlan, analysis: Analysis) -> str:
    image = plan.steps[0].params.get("image", "debian:stable-slim") if plan.steps else "debian:stable-slim"
    lines = [
        HEADER,
        f"FROM {image}",
        "",
        "RUN apt-get update && apt-get install -y --no-install-recommends \\",
        f"      {' '.join(sorted(set(plan.packages))) or 'ca-certificates'} \\",
        "    && rm -rf /var/lib/apt/lists/*",
        "",
        "WORKDIR /app",
        "COPY . /app",
        "",
    ]
    if plan.ld_library_path:
        lines.append(f'ENV LD_LIBRARY_PATH={":".join(plan.ld_library_path)}')
    for k, v in sorted(plan.env.items()):
        lines.append(f"ENV {k}={v}")
    lines.append("")
    entry = _container_entry(plan, analysis)
    lines.append("ENTRYPOINT " + _json_array(entry))
    lines.append("")
    return "\n".join(lines)


def _container_entry(plan: StrategyPlan, analysis: Analysis) -> list[str]:
    """Like :func:`_entry_argv`, but rewrite the host path to the mount point."""
    mounted = "/app/" + os.path.basename(analysis.path)
    entry = _entry_argv(plan, analysis)
    return [mounted if a == analysis.path else a for a in entry]



def _json_array(items: list[str]) -> str:
    return json.dumps(items)


def _entry_argv(plan: StrategyPlan, analysis: Analysis) -> list[str]:
    for step in plan.steps:
        if step.kind == "exec":
            argv = step.params.get("argv")
            if isinstance(argv, list) and argv:
                return [str(x) for x in argv]
    return [os.path.basename(analysis.path)]


def compile_runner(plan: StrategyPlan, analysis: Analysis, profile_dir: Path) -> str:
    """The main entrypoint script that a remembered profile re-executes."""
    lines = [
        "#!/bin/sh",
        HEADER,
        f"# Application: {os.path.basename(analysis.path)}",
        f"# Strategy:   {plan.strategy} (runtime {plan.runtime})",
        f"# Confidence: {plan.confidence:.2f}",
        "set -e",
        "",
        'HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)',
        f'LITON_APP={_sh_quote(analysis.path)}',
        "",
    ]

    # Unpack step: materialise a cached rootfs once.
    unpack_steps = [s for s in plan.steps if s.kind == "unpack"]
    for step in unpack_steps:
        lines += _emit_unpack(step)

    env_file = profile_dir / "run.env"
    lines += [
        f'if [ -f "$HERE/run.env" ]; then',
        '  . "$HERE/run.env"',
        "fi",
        "",
    ]

    # Loader override.
    loader_step = next((s for s in plan.steps if s.kind == "use_loader"), None)
    if loader_step:
        loader = loader_step.params.get("loader", loader_step.detail)
        target = loader_step.params.get("target", analysis.path)
        lines += [
            f'LITON_LOADER={_sh_quote(loader)}',
            f'LITON_TARGET={_sh_quote(target)}',
            "",
        ]

    if plan.runtime in ("docker", "podman"):
        lines += _emit_container(plan, analysis)
    else:
        lines += _emit_host(plan, analysis)

    return "\n".join(lines)


def _translate_step(plan: StrategyPlan):
    return next((s for s in plan.steps if s.kind == "translate"), None)


def _translator_of(plan: StrategyPlan) -> Translator | None:
    """The translator to launch through, from the step or the plan field."""
    if plan.translator:
        return Translator.from_dict(plan.translator)
    step = _translate_step(plan)
    if step:
        return Translator.from_dict(step.params.get("translator") or {})
    return None


def _emit_translate(plan: StrategyPlan, analysis: Analysis) -> list[str]:
    """Launch through a real translator (FEX / box64 / qemu), caches pinned.

    The translator's own caches are placed inside the profile, so the first
    launch pays for translation and every later launch reuses it.
    """
    tr = _translator_of(plan) or Translator()
    kind = tr.kind or "translator"
    prefix = " ".join(_sh_quote(x) for x in tr.argv_prefix)
    lines = [
        f"# Translation backend: {kind} ({tr.guest_arch} on {tr.host_arch})",
        f"LITON_TRANSLATOR={_sh_quote(tr.path)}",
        'if [ ! -x "$LITON_TRANSLATOR" ]; then',
        f'  echo "[liton] translator {kind} is missing: $LITON_TRANSLATOR" >&2',
        "  exit 127",
        "fi",
    ]

    if tr.kind == "fex":
        # Keep FEX's data and JIT cache inside the profile. This is what makes
        # the translation persist: the code cache is written once and reloaded
        # on every subsequent run instead of being retranslated.
        lines += [
            f'FEX_APP_DATA_LOCATION="$HERE/fex-emu/"',
            f'FEX_APP_CACHE_LOCATION="$HERE/cache/fex-emu/"',
            "export FEX_APP_DATA_LOCATION FEX_APP_CACHE_LOCATION",
            'mkdir -p "$FEX_APP_DATA_LOCATION" "$FEX_APP_CACHE_LOCATION"',
        ]
        if tr.sysroot:
            lines.append(f'FEX_ROOTFS={_sh_quote(tr.sysroot)}')
            lines.append("export FEX_ROOTFS")
        else:
            # No rootfs was found when this profile was compiled; accept one
            # supplied at run time so installing it later is enough.
            lines += [
                'if [ -z "${FEX_ROOTFS:-}" ] && [ -n "${LITON_FEX_ROOTFS:-}" ]; then',
                '  FEX_ROOTFS="$LITON_FEX_ROOTFS"',
                "  export FEX_ROOTFS",
                "fi",
            ]

    for key, value in sorted(tr.env.items()):
        if key in ("FEX_APP_DATA_LOCATION", "FEX_APP_CACHE_LOCATION"):
            continue
        lines.append(f"export {key}={_sh_quote(value)}")

    lines += [
        "",
        f'exec "$LITON_TRANSLATOR" {prefix} "$LITON_APP" "$@"',
        "",
    ]
    return lines


def _emit_host(plan: StrategyPlan, analysis: Analysis) -> list[str]:
    if _translator_of(plan):
        return _emit_translate(plan, analysis)
    entry = _entry_argv(plan, analysis)
    entry_q = " ".join(_render_arg(x) for x in entry)
    lines = [
        '# exec the application, forwarding every argument',
        'if [ -n "$LITON_LOADER" ] && [ -x "$LITON_LOADER" ]; then',
        f'  exec "$LITON_LOADER" --library-path "${{LD_LIBRARY_PATH:-}}" "$LITON_TARGET" "$@"',
        "fi",
        f"exec {entry_q} \"$@\"",
        "",
    ]
    return lines


def _emit_unpack(step) -> list[str]:
    src = step.params.get("source", step.detail)
    tool = step.params.get("tool", "tar")
    out = step.params.get("dest", "${HERE}/rootfs")
    if tool == "appimage-extract":
        return [
            f'LITON_ROOTFS="$HERE/rootfs"',
            'if [ ! -d "$LITON_ROOTFS" ]; then',
            '  echo "[liton] extracting AppImage rootfs (one time)..." >&2',
            '  TMPD=$(mktemp -d)',
            '  ( cd "$TMPD" && "$LITON_APP" --appimage-extract >/dev/null )',
            '  mkdir -p "$LITON_ROOTFS"',
            '  cp -a "$TMPD"/squashfs-root/. "$LITON_ROOTFS"/',
            '  rm -rf "$TMPD"',
            "fi",
            "",
        ]
    if tool == "unzip":
        return [
            f'LITON_ROOTFS="$HERE/rootfs"',
            'if [ ! -d "$LITON_ROOTFS" ]; then',
            f'  mkdir -p "$LITON_ROOTFS"',
            f'  unzip -q {_sh_quote(src)} -d "$LITON_ROOTFS"',
            "fi",
            "",
        ]
    return [
        f'LITON_ROOTFS="$HERE/rootfs"',
        'if [ ! -d "$LITON_ROOTFS" ]; then',
        f'  mkdir -p "$LITON_ROOTFS"',
        f'  tar -xf {_sh_quote(src)} -C "$LITON_ROOTFS"',
        "fi",
        "",
    ]


def _render_arg(value: str) -> str:
    """Quote an argv element, but let a leading ${LITON_ROOTFS} expand."""
    if value.startswith("${LITON_ROOTFS}"):
        rest = value[len("${LITON_ROOTFS}"):]
        return f'"$LITON_ROOTFS"{_sh_quote(rest)}'
    return _sh_quote(value)


def _emit_container(plan: StrategyPlan, analysis: Analysis) -> list[str]:
    runtime = plan.runtime if plan.runtime in ("docker", "podman") else "docker"
    entry = _entry_argv(plan, analysis)
    entry_q = " ".join(_sh_quote(x) for x in entry)
    lines = [
        f'LITON_RUNTIME={_sh_quote(runtime)}',
        'if ! command -v "$LITON_RUNTIME" >/dev/null 2>&1; then',
        f'  echo "[liton] $LITON_RUNTIME is required for this profile but is not installed" >&2',
        "  exit 127",
        "fi",
        'IMAGE="liton/' + analysis.path.strip("/").replace("/", "-") + ':profile"',
        'if ! "$LITON_RUNTIME" image inspect "$IMAGE" >/dev/null 2>&1; then',
        '  echo "[liton] building container image (one time)..." >&2',
        '  "$LITON_RUNTIME" build -t "$IMAGE" "$HERE"',
        "fi",
        f'exec "$LITON_RUNTIME" run --rm -i \\',
        '  -v "$LITON_APP:/app/' + os.path.basename(analysis.path) + ':ro" \\',
        '  "$IMAGE" ' + entry_q + ' "$@"',
        "",
    ]
    return lines


def compile_all(plan: StrategyPlan, analysis: Analysis, profile_dir: Path) -> list[Path]:
    """Write every artifact for *plan* into *profile_dir* and return the paths."""
    profile_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    (profile_dir / "run.env").write_text(compile_env(plan))
    written.append(profile_dir / "run.env")

    install = profile_dir / "install-deps.sh"
    install.write_text(compile_install(plan))
    _make_executable(install)
    written.append(install)

    runner = profile_dir / "run.sh"
    runner.write_text(compile_runner(plan, analysis, profile_dir))
    _make_executable(runner)
    written.append(runner)

    if plan.runtime in ("docker", "podman"):
        dockerfile = profile_dir / "Dockerfile"
        dockerfile.write_text(compile_dockerfile(plan, analysis))
        written.append(dockerfile)

    return written


def _make_executable(path: Path) -> None:
    mode = path.stat().st_mode
    path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

"""Compiler, verifier and CLI tests."""

from __future__ import annotations

import json
import os
import subprocess

from liton.analysis import analyze
from liton.cli import main
from liton.compiler import (compile_all, compile_dockerfile, compile_env,
                            compile_install, compile_runner)
from liton.planner import plan_rules
from liton.runner import Engine
from liton.store import plan_from_dict
from liton.util import Log
from liton.verify import verify_profile


def quiet():
    return Log("error")


def sh_syntax_ok(path) -> bool:
    return subprocess.run(["/bin/sh", "-n", str(path)]).returncode == 0


def test_env_artifact_has_ld_library_path(bundled_app, tmp_path):
    a = analyze(str(bundled_app), log=quiet())
    plan = plan_rules(a)
    text = compile_env(plan)
    assert "LD_LIBRARY_PATH" in text
    assert "lib" in text


def test_install_script_quotes_packages(missing_dep_app):
    a = analyze(str(missing_dep_app), log=quiet())
    text = compile_install(plan_rules(a))
    assert "apt-get install -y libsdl2-2.0-0" in text


def test_install_script_noop_without_packages(simple_app):
    a = analyze(str(simple_app), log=quiet())
    text = compile_install(plan_rules(a))
    assert "exit 0" in text


def test_compiled_scripts_are_valid_shell(simple_app, bundled_app, missing_dep_app, tmp_path):
    for app in (simple_app, bundled_app, missing_dep_app):
        a = analyze(str(app), log=quiet())
        plan = plan_rules(a)
        out = compile_all(plan, a, tmp_path / app.name)
        for art in out:
            if art.suffix == ".sh":
                assert sh_syntax_ok(art), art


def test_runner_script_uses_loader_when_present(tmp_path):
    a = analyze("/bin/ls", log=quiet())
    plan = plan_rules(a)
    plan.steps.insert(0, __import__("liton.models", fromlist=["Step"]).Step(
        "use_loader", "/lib64/ld-linux-x86-64.so.2",
        {"loader": "/lib64/ld-linux-x86-64.so.2", "target": "/bin/ls"}))
    text = compile_runner(plan, a, tmp_path)
    assert "LITON_LOADER" in text
    assert "--library-path" in text


def test_dockerfile_mounts_target_at_app_path(pe_like, tmp_path):
    a = analyze(str(pe_like), log=quiet())
    plan = plan_rules(a)
    text = compile_dockerfile(plan, a)
    assert "FROM scottyhardy/docker-wine" in text
    assert f"/app/{pe_like.name}" in text
    assert text.count("# Generated by Liton") == 1


def test_verify_passes_for_good_profile(simple_app):
    engine = Engine(log=quiet())
    profile = engine.translate(str(simple_app))
    result = verify_profile(profile, execute=True, log=quiet())
    assert result.ok, result.render()
    assert any(c[0] == "dynamic loader resolves target" and c[1] for c in result.checks)


def test_verify_passes_for_bundled_library_app(bundled_app):
    """The profile's own LD_LIBRARY_PATH must count when verifying libraries."""
    engine = Engine(log=quiet())
    profile = engine.translate(str(bundled_app))
    result = verify_profile(profile, execute=True, log=quiet())
    assert result.ok, result.render()
    libs = next(c for c in result.checks if c[0] == "shared libraries resolvable")
    assert libs[1], libs[2]


def test_verify_reports_missing_target(simple_app, tmp_path):
    engine = Engine(log=quiet())
    profile = engine.translate(str(simple_app))
    profile.source_path = str(tmp_path / "gone")
    result = verify_profile(profile, log=quiet())
    assert not result.ok


